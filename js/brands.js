const HOSTS = [
  [/(^|\.)google\.[a-z.]+$/, "google"],
  [/(^|\.)(youtube\.com|youtu\.be)$/, "youtube"],
  [/(^|\.)notion\.(so|com|site)$/, "notion"],
  [/(^|\.)github\.com$/, "github"],
  [/(^|\.)(x|twitter)\.com$/, "x"],
  [/(^|\.)spotify\.com$/, "spotify"],
];

/** @param {string} url @returns {string | null} brand key */
export function brandFor(url) {
  let host;
  try {
    host = new URL(url).hostname;
  } catch {
    return null;
  }
  return HOSTS.find(([re]) => re.test(host))?.[1] || null;
}

