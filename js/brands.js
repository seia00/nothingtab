/* Second-level-domain guess for Simple Icons ("linear.app" → "linear",
   "bbc.co.uk" → "bbc"). A wrong guess just 404s and the tile falls back to
   its monogram. */
const SECOND_LEVEL = new Set(["co", "com", "ac", "or", "ne", "go", "gov", "org", "net", "edu"]);

/** @param {string} url @returns {string | null} */
export function simpleIconSlug(url) {
  let host;
  try {
    host = new URL(url).hostname.replace(/^www\./, "");
  } catch {
    return null;
  }
  const labels = host.split(".");
  if (labels.length < 2) return null;
  let i = labels.length - 2;
  if (SECOND_LEVEL.has(labels[i]) && labels.length >= 3) i -= 1;
  const slug = labels[i].toLowerCase();
  return /^[a-z0-9]{2,40}$/.test(slug) ? slug : null;
}
