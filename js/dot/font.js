/**
 * @typedef {{ height: number, spacing: number, glyphs: Record<string, string[]>,
 *   get: (ch: string) => string[] | null }} Font
 */
function makeFont(height, spacing, glyphs) {
  return {
    height,
    spacing,
    glyphs,
    get(ch) {
      return glyphs[ch] || glyphs[ch.toUpperCase()] || glyphs[ch.toLowerCase()] || null;
    },
  };
}

export const FONT_5x7 = makeFont(7, 1, G57);
export const FONT_BIG = makeFont(11, 3, GBIG);
export const FONT_3x5 = makeFont(5, 1, G35);

/**
 * Width in dots. Characters the font lacks are skipped, same as when drawn.
 * @param {string} str @param {Font} font @param {number} [spacing]
 */
export function measure(str, font, spacing = font.spacing) {
  let w = 0;
  let n = 0;
  for (const ch of str) {
    const rows = font.get(ch);
    if (!rows) continue;
    w += rows[0].length;
    n++;
  }
  return n ? w + (n - 1) * spacing : 0;
}
